// Safe LocalStorage Helper
export const loadStore = (key, fallback) => {
  try {
    const item = localStorage.getItem(`medqueue_${key}`);
    return item ? JSON.parse(item) : fallback;
  } catch (err) {
    console.warn(`Error loading ${key} from storage:`, err);
    return fallback;
  }
};

export const saveStore = (key, data) => {
  try {
    localStorage.setItem(`medqueue_${key}`, JSON.stringify(data));
  } catch (err) {
    console.warn(`Error saving ${key} to storage:`, err);
  }
};
